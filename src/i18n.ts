function interpolate(message: string, variables: Record<string, unknown>): string {
  return message.replace(/\{([A-Za-z0-9_]+)\}/gu, (_match, key: string) =>
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : `{${key}}`,
  );
}

export function createTranslator(): (key: string, variables?: Record<string, unknown>) => string {
  const locale = String(getLanguage?.() || "en").toLowerCase().split("-")[0];
  const catalog = locale === "es" ? ES : EN;
  return (key, variables = {}) => interpolate(catalog[key] ?? EN[key] ?? key, variables);
}
